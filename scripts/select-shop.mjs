// Points the app at one shop: writes shops/current.ts from the SHOP env variable.
// Runs on its own before `dev`, `build` and after `npm install`.
//   SHOP=cafe-roma npm run dev
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const DEFAULT_SHOP = "horno-lento";
const slug = (process.env.SHOP || DEFAULT_SHOP).trim();
const dir = new URL(`../shops/${slug}/`, import.meta.url);

if (!/^[a-z0-9][a-z0-9-]*$/.test(slug) || !existsSync(new URL("shop.ts", dir)) || !existsSync(new URL("menu.json", dir))) {
  console.error(`SHOP="${slug}" no existe: tiene que haber una carpeta shops/${slug} con shop.ts y menu.json.`);
  console.error(`Para crear una nueva: npm run new-shop ${slug}`);
  process.exit(1);
}


const hasStock = existsSync(new URL("stock-photos.json", dir));
const source = `// Generated by scripts/select-shop.mjs for SHOP=${slug}. Don't edit: it's rewritten on every dev and build.
export { default as shop } from "./${slug}/shop";
export { default as menu } from "./${slug}/menu.json";
${hasStock ? `export { default as stockPhotos } from "./${slug}/stock-photos.json";` : "export const stockPhotos = {};"}
export const slug = "${slug}";
`;

writeIfChanged("../shops/current.ts", source);

// Fonts live apart from current.ts because next.config.ts imports that one, and next/font only runs in the app.
const fonts = existsSync(new URL("fonts.ts", dir)) ? `./${slug}/fonts` : "./fonts";
writeIfChanged("../shops/current-fonts.ts", `// Generated by scripts/select-shop.mjs for SHOP=${slug}. Don't edit: it's rewritten on every dev and build.
export { display, body } from "${fonts}";
`);

function writeIfChanged(path, text) {
  const target = new URL(path, import.meta.url);
  if (!existsSync(target) || readFileSync(target, "utf8") !== text) writeFileSync(target, text);
}

console.log(`Tienda: ${slug}`);

// White text sits on the brand color (buttons, badges): warn if it would be hard to read.
const brand = readFileSync(new URL("shop.ts", dir), "utf8").match(/\bbrand:\s*"#([0-9a-f]{6})"/i)?.[1];
if (brand) {
  const luminance = [0, 2, 4]
    .map((i) => parseInt(brand.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
    .reduce((sum, c, i) => sum + c * [0.2126, 0.7152, 0.0722][i], 0);
  const contrast = 1.05 / (luminance + 0.05);
  if (contrast < 4.5) {
    console.warn(`Aviso: el texto blanco sobre #${brand} tiene contraste ${contrast.toFixed(1)}:1 (mínimo 4.5). Usá un color de marca más oscuro.`);
  }
}
